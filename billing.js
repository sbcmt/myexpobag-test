/** Browser-side Stripe Sandbox Checkout client; secrets live only in Worker. */
import {initializeApp,getApps,getApp} from 'https://www.gstatic.com/firebasejs/10.12.5/firebase-app.js';
import {getAuth,onAuthStateChanged} from 'https://www.gstatic.com/firebasejs/10.12.5/firebase-auth.js';
const $=id=>document.getElementById(id);
const config=window.MEB_FIREBASE_CONFIG||{};
const base=(window.MEB_BILLING_API_URL||'').replace(/\/$/,'');
let user;
function status(message,error=false){$('payment-status').textContent=message;$('payment-status').className=error?'status error':'status';}
function setDisabled(buttons,disabled){for(const id of buttons)$(id).disabled=disabled;}
async function callWorker(path,body={}){
  if(!/^https:\/\/[a-z0-9.-]+\.workers\.dev$/i.test(base))throw new Error('Cloudflare WorkerのURLが設定されていません。');
  if(!user)throw new Error('ログインし直してください。');
  const token=await user.getIdToken(true);
  const resp=await fetch(base+path,{method:'POST',headers:{'authorization':`Bearer ${token}`,'content-type':'application/json'},body:JSON.stringify(body)});
  const data=await resp.json().catch(()=>({}));
  if(!resp.ok||!/^https:\/\//.test(data.url||''))throw new Error(data.error||'決済画面を開けませんでした。');
  // Checkout / Portal URLs are generated by the server, never by query parameters.
  if(!/^https:\/\/(checkout\.stripe\.com|billing\.stripe\.com)\//.test(data.url))throw new Error('Stripe以外への移動を拒否しました。');
  location.assign(data.url);
}
async function init(u){
 user=u;
 if(!u){location.replace('./login.html');return;}
 try{await window.MEB_PLAN?.ready?.();}catch{}
 const plan=window.MEB_PLAN?.current?.()||{plan:'free'};
 const isPro=window.MEB_PLAN?.isPro?.()||false;
 const tester=window.MEB_PLAN?.isTester?.()||false;
 $('plan-status').textContent=`現在のプラン：${isPro?'Pro.':'Free'}`;
 setDisabled(['buy-monthly','buy-yearly'],isPro);
 $('manage-billing').disabled=!isPro||tester;
 const query=new URLSearchParams(location.search);
 if(query.get('payment')==='success')status('Stripe決済の処理を確認しています。すぐに切り替わらない場合は「プラン状態を再確認」を押してください。');
 else if(query.get('payment')==='cancel')status('テスト決済をキャンセルしました。');
 if(!base)status('Workerを作成した後、billing-config.jsにURLを設定してください。',true);
}
$('buy-monthly').addEventListener('click',()=>callWorker('/api/checkout',{plan:'monthly'}).catch(e=>status(e.message,true)));
$('buy-yearly').addEventListener('click',()=>callWorker('/api/checkout',{plan:'yearly'}).catch(e=>status(e.message,true)));
$('manage-billing').addEventListener('click',()=>callWorker('/api/portal').catch(e=>status(e.message,true)));
$('refresh').addEventListener('click',()=>location.replace('./billing.html?refresh='+Date.now()));
const app=getApps().length?getApp():initializeApp(config);
onAuthStateChanged(getAuth(app),init,()=>status('ログイン状態を確認できませんでした。',true));
